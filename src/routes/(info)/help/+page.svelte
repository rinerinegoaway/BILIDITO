<h1>Help</h1>

<h2>Why do I need to verify my ID?</h2>
<p>
	Verification keeps scammers out. You can browse and message without it, but posting listings and
	requesting to buy need a verified account. Go to <a href="/verify">Verify your account</a>.
</p>

<h2>Who can see my ID?</h2>
<p>Only BILIDITO administrators, to check it. Other members never see your ID.</p>

<h2>How do I pay?</h2>
<p>
	Directly to the seller, usually cash on delivery (COD) through the rider or courier. BILIDITO
	doesn't process payments. Never pay before you've checked the item.
</p>

<h2>How does delivery work?</h2>
<p>
	After a seller accepts your request, you and the seller agree on how to ship it locally: a rider,
	a delivery van or a courier outlet. These are independent providers, not BILIDITO. Delivery fees
	shown are estimates; confirm the final fee with the seller or courier.
</p>

<h2>I forgot my password</h2>
<p>
	Use <a href="/forgot-password">Forgot password</a> on the login page to get a reset link by email.
</p>
