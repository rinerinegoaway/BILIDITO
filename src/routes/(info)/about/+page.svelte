<h1>About BILIDITO</h1>
<p>
	BILIDITO is a local buy &amp; sell marketplace for Cagayan Province. Our goal is simple:
	<strong>Buy Nearby. Sell Safely. Connect Locally.</strong>
</p>
<h2>What makes BILIDITO different</h2>
<ul>
	<li><strong>Verified members.</strong> Sellers confirm their identity with a government ID.</li>
	<li><strong>Local first.</strong> Listings from your own town show up first.</li>
	<li><strong>Ratings &amp; reviews</strong> after every completed transaction.</li>
	<li><strong>Report &amp; moderation.</strong> Our team reviews reported listings and users.</li>
</ul>
<h2>How buying works</h2>
<p>
	Find an item, message the seller, then send a <em>Request to Buy</em>. Once the seller accepts,
	you agree with the seller on how to ship it: a local rider, a delivery van or a courier outlet.
	BILIDITO does not handle payments: you pay the seller directly, ideally cash on delivery after
	you've checked the item.
</p>
<p>We're starting in Cagayan and will grow to more of Northern Luzon as our community grows.</p>
