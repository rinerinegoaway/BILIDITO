<h1>Privacy Policy</h1>
<DraftNotice />

<p>
	BILIDITO processes personal data in line with the Philippine Data Privacy Act of 2012 (Republic
	Act No. 10173).
</p>

<h2>What we collect</h2>
<ul>
	<li>
		<strong>Account details:</strong> full name, username, email, mobile number, password (stored only
		as a secure hash).
	</li>
	<li>
		<strong>Location:</strong> your province, municipality/city and barangay. We never ask for your house
		address.
	</li>
	<li>
		<strong>Identity verification:</strong> photos of the government ID you choose to submit. We do not
		ask for your ID number.
	</li>
	<li><strong>Marketplace activity:</strong> listings, messages, orders, ratings and reports.</li>
</ul>

<h2>Who can see what</h2>
<ul>
	<li>
		<strong>Public:</strong> your name, username, profile photo, verified badge, town, ratings, reviews
		and listings.
	</li>
	<li>
		<strong>Never public:</strong> your email, mobile number, barangay, password and ID documents.
	</li>
	<li>
		<strong>Only the other party of an order:</strong> the delivery address you agree on.
	</li>
	<li>
		<strong>ID documents:</strong> only authorised BILIDITO administrators, solely to verify your identity.
		Every view is logged.
	</li>
</ul>

<h2>How we protect it</h2>
<p>
	ID images are stored in private storage with no public link. Location data embedded in uploaded
	photos is removed. Access to administrative tools is restricted and audited.
</p>

<h2>How long we keep it</h2>
<p>
	We keep account and transaction records while your account exists and as required by law. We plan
	to delete ID images after verification is decided, keeping only the decision record. Retention
	periods will be finalised before launch.
</p>

<h2>Your rights</h2>
<p>
	You may request access to, correction of, or deletion of your personal data, and you may object to
	its processing, as provided by RA 10173. Contact us through the <a href="/contact">Contact</a>
	page.
</p>
